MODEL (
  name main_models.pbp_completed_events,
  kind VIEW,
  grain (event_key),
  audits (estimated_contract_complete, min_row_count(threshold := 1), unique_grain(columns := (event_key))),
  description 'Complete-value event spine for PBP games across history. Recorded outcomes remain unchanged; counts and contact geometry use additive completion artifacts. Child runner, fielding and pitch evidence remains available at its original grain.'
);

SELECT
    e.* REPLACE (
        p.completed_count_balls AS count_balls,
        p.completed_count_strikes AS count_strikes,
        coalesce(g.trajectory, e.batted_trajectory::VARCHAR) AS batted_trajectory,
        coalesce(g.handler_position, e.batted_to_fielder) AS batted_to_fielder,
        coalesce(g.general_location, e.batted_location_general::VARCHAR) AS batted_location_general,
        coalesce(g.location_depth_modifier, e.batted_location_depth::VARCHAR) AS batted_location_depth,
        coalesce(g.location_angle, e.batted_location_angle::VARCHAR) AS batted_location_angle,
        coalesce(g.contact_strength, e.batted_contact_strength::VARCHAR) AS batted_contact_strength
    ),
    e.count_balls AS raw_count_balls,
    e.count_strikes AS raw_count_strikes,
    e.batted_trajectory::VARCHAR AS raw_batted_trajectory,
    e.batted_to_fielder AS raw_batted_to_fielder,
    e.batted_location_general::VARCHAR AS raw_batted_location_general,
    e.batted_location_depth::VARCHAR AS raw_batted_location_depth,
    e.batted_location_angle::VARCHAR AS raw_batted_location_angle,
    e.batted_contact_strength::VARCHAR AS raw_batted_contact_strength,
    g.location_side,
    g.location_depth,
    g.location_edge,
    g.standardized_trajectory,
    g.p_standardized_ground_ball,
    g.p_standardized_fly,
    g.p_standardized_line_drive,
    g.p_standardized_pop_up,
    g.trajectory_method,
    g.general_location_method,
    g.location_angle_method,
    g.location_depth_modifier_method,
    g.contact_strength_method,
    g.handler_position_method,
    g.standardized_trajectory_method,
    g.artifact_id AS geometry_artifact_id,
    v.expected_runs_change_raw AS raw_expected_runs_change,
    v.expected_runs_change,
    v.expected_home_win_change_raw AS raw_expected_home_win_change,
    v.expected_home_win_change,
    v.expected_batting_win_change_raw AS raw_expected_batting_win_change,
    v.expected_batting_win_change,
    v.run_expectancy_start,
    v.run_expectancy_end,
    v.home_win_expectancy_start,
    v.home_win_expectancy_end,
    v.expected_runs_change_method,
    v.expected_win_change_method,
    v.artifact_id AS value_artifact_id,
    v.model_name AS value_model_name,
    v.model_version AS value_model_version,
    v.source_snapshot_id AS value_source_snapshot_id,
    v.method AS value_method,
    v.observed_status AS value_observed_status,
    v.confidence_status AS value_confidence_status,
    v.weak_identification_flag AS value_weak_identification_flag,
    p.* EXCLUDE (event_key, game_id, event_id, season, plate_appearance_result, count_balls, count_strikes)
FROM main_models.stg_events e
JOIN main_models.pbp_completed_pitches p USING (event_key)
LEFT JOIN main_models.pbp_completed_geometry g USING (event_key)
LEFT JOIN main_models.pbp_completed_event_values v USING (event_key)
