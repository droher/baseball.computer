MODEL (
  name main_models.model_input_geometry,
  kind VIEW,
  description 'Modeling dataset for the batted-ball geometry posterior. Emits one row per (event_key, geometry_dimension) with class = COALESCE(raw_value, deduced_value) and is_observed_class = (observed_status IN observed, derived). Per-class fan-out (full class universe per dim) deferred until the DL class axis is defined. Driver = event_observation_geometry filtered to observed_status IN observed / derived / unknown_code / missing. Target-population filter: event_level.',
  grain (event_key, geometry_dimension),
  columns (
    event_key UINTEGER,
    geometry_dimension VARCHAR,
    class VARCHAR,
    is_observed_class BOOLEAN,
    observed_status VARCHAR,
    sentinel_type VARCHAR,
    raw_value VARCHAR,
    deduced_value VARCHAR,
    source_acquisition_status VARCHAR,
    data_error_risk VARCHAR,
    model_input_eligible BOOLEAN,
    game_id VARCHAR,
    season SMALLINT,
    league VARCHAR,
    game_type GAME_TYPE,
    source_type VARCHAR,
    source_family VARCHAR,
    target_population_status VARCHAR,
    park_id PARK_ID,
    park_episode_status VARCHAR,
    scorer VARCHAR,
    inputter VARCHAR,
    translator VARCHAR,
    affiliated_team TEAM_ID,
    inning_start UTINYINT,
    frame_start FRAME,
    base_state_start UTINYINT,
    outs_start UTINYINT,
    score_margin TINYINT,
    leverage_index DOUBLE,
    leverage_bucket VARCHAR,
    runs_on_play UTINYINT,
    hit_or_out BOOLEAN,
    batter_id VARCHAR,
    pitcher_id VARCHAR,
    batter_hand HAND,
    pitcher_hand HAND,
    batting_team_id TEAM_ID,
    fielding_team_id TEAM_ID,
    personnel_confidence VARCHAR,
    context_confidence VARCHAR,
    exposure_status VARCHAR,
    result_family VARCHAR,
    alignment_regime VARCHAR,
    dl_artifact_id VARCHAR,
    dl_p_class DOUBLE[],
    holdout_flags STRUCT(
      is_heldout_scorer BOOLEAN,
      is_heldout_park BOOLEAN,
      is_heldout_alignment_regime BOOLEAN,
      is_heldout_source_acquisition_block BOOLEAN,
      is_heldout_season_block BOOLEAN,
      is_heldout_aggregate_total BOOLEAN,
      is_heldout_player_group BOOLEAN
    ),
    primary_fold VARCHAR,
    training_weight DOUBLE,
    source_snapshot_id VARCHAR
  ),
  column_descriptions (
    event_key = @doc('event_key'),
    geometry_dimension = 'Atomic geometry dimension (trajectory, location_side, etc.). One row per (event_key, geometry_dimension).',
    class = 'COALESCE(raw_value, deduced_value). NULL when observed_status is missing or unknown_code with no inference.',
    is_observed_class = 'BOOLEAN. TRUE iff observed_status IN (observed, derived) — class was either directly recorded or deterministically inferred.',
    observed_status = 'event_observation_geometry.observed_status (filtered to observed / derived / unknown_code / missing).',
    sentinel_type = 'event_observation_geometry.sentinel_type.',
    raw_value = 'event_observation_geometry.raw_value.',
    deduced_value = 'event_observation_geometry.deduced_value.',
    source_acquisition_status = 'event_observation_geometry.source_acquisition_status.',
    data_error_risk = 'event_observation_geometry.data_error_risk.',
    model_input_eligible = 'event_observation_geometry.model_input_eligible.',
    primary_fold = 'Default game-hash split. HASH(game_id) mod 100 -> [0,69]=TRAIN, [70,84]=VALIDATE, [85,99]=TEST.',
    training_weight = '1.0 when data_error_risk = none else 0.0.',
    source_snapshot_id = 'Stamp from the source_snapshot_id var.',
    holdout_flags = 'STRUCT of 7 stress-test holdout BOOLEANs, NULL until DL supplements land.',
    dl_artifact_id = 'dl_proposal_manifest.dl_artifact_id, NULL until DL supplements land.',
    dl_p_class = 'dl_proposal_manifest.dl_p_class, NULL until DL supplements land.'
  ),
  audits (
    not_null(columns := (event_key, geometry_dimension, observed_status, game_id, season, primary_fold, source_snapshot_id)),
    unique_grain(columns := (event_key, geometry_dimension)),
    accepted_values(column := geometry_dimension, is_in := (
      'trajectory', 'location_side', 'location_depth', 'location_edge',
      'general_location', 'ball_handler_position', 'pulled_opposite'
    )),
    accepted_values(column := observed_status, is_in := ('observed', 'derived', 'unknown_code', 'missing')),
    accepted_values(column := primary_fold, is_in := ('TRAIN', 'VALIDATE', 'TEST')),
    accepted_values(column := alignment_regime, is_in := (
      'pre_shift_era', 'shift_growth_era', 'full_shift_era', 'post_restriction'
    )),
    accepted_values(column := leverage_bucket, is_in := ('low', 'medium', 'high')),
    relationships(column := event_key, to_model := main_models.event_observation_context, to_column := event_key)
  )
);

SELECT
    o.event_key,
    o.dimension AS geometry_dimension,
    COALESCE(o.raw_value, o.deduced_value) AS class,
    (o.observed_status IN ('observed', 'derived')) AS is_observed_class,
    o.observed_status,
    o.sentinel_type,
    o.raw_value,
    o.deduced_value,
    o.source_acquisition_status,
    o.data_error_risk,
    o.model_input_eligible,
    c.game_id,
    c.season,
    c.league,
    c.game_type,
    c.source_type,
    c.source_family,
    c.target_population_status,
    c.park_id,
    c.park_episode_status,
    c.scorer,
    c.inputter,
    c.translator,
    c.affiliated_team,
    c.inning_start,
    c.frame_start,
    c.base_state_start,
    c.outs_start,
    c.score_margin,
    c.leverage_index,
    c.leverage_bucket,
    c.runs_on_play,
    c.hit_or_out,
    c.batter_id,
    c.pitcher_id,
    c.batter_hand,
    c.pitcher_hand,
    c.batting_team_id,
    c.fielding_team_id,
    c.personnel_confidence,
    c.context_confidence,
    c.exposure_status,
    c.result_family,
    c.alignment_regime,
    p.dl_artifact_id,
    p.dl_p_class,
    STRUCT_PACK(
        is_heldout_scorer := s.is_heldout_scorer,
        is_heldout_park := s.is_heldout_park,
        is_heldout_alignment_regime := s.is_heldout_alignment_regime,
        is_heldout_source_acquisition_block := s.is_heldout_source_acquisition_block,
        is_heldout_season_block := s.is_heldout_season_block,
        is_heldout_aggregate_total := s.is_heldout_aggregate_total,
        is_heldout_player_group := s.is_heldout_player_group
    ) AS holdout_flags,
    CASE
        WHEN (HASH(c.game_id)::HUGEINT % 100) < 70 THEN 'TRAIN'
        WHEN (HASH(c.game_id)::HUGEINT % 100) < 85 THEN 'VALIDATE'
        ELSE 'TEST'
    END AS primary_fold,
    CASE WHEN o.data_error_risk = 'none' THEN 1.0 ELSE 0.0 END AS training_weight,
    @VAR('source_snapshot_id', 'dev') AS source_snapshot_id
FROM main_models.event_observation_geometry AS o
INNER JOIN main_models.event_observation_context AS c USING (event_key)
LEFT JOIN main_models.dl_proposal_manifest AS p
    ON p.event_key = o.event_key AND p.dimension = o.dimension
LEFT JOIN main_models.stress_holdout_registry AS s USING (event_key)
WHERE c.target_population_status = 'event_level'
  AND o.observed_status IN ('observed', 'derived', 'unknown_code', 'missing')
