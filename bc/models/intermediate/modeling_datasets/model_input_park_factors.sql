WITH ofs AS (
    SELECT
        event_key,
        plate_appearances,
        at_bats,
        hits,
        singles,
        doubles,
        triples,
        home_runs,
        walks,
        intentional_walks,
        hit_by_pitches,
        strikeouts,
        balls_in_play,
        runs
    FROM main_models.event_offense_stats
    WHERE baserunner = 'Batter'
)

SELECT
    c.event_key,
    CASE WHEN es.batting_side = 'Home' THEN 'home' ELSE 'away' END AS home_away,
    es.is_interleague,
    COALESCE(ofs.plate_appearances, 0) AS plate_appearances,
    COALESCE(ofs.at_bats, 0) AS at_bats,
    COALESCE(ofs.hits, 0) AS hits,
    COALESCE(ofs.singles, 0) AS singles,
    COALESCE(ofs.doubles, 0) AS doubles,
    COALESCE(ofs.triples, 0) AS triples,
    COALESCE(ofs.home_runs, 0) AS home_runs,
    COALESCE(ofs.walks, 0) AS walks,
    COALESCE(ofs.intentional_walks, 0) AS intentional_walks,
    COALESCE(ofs.hit_by_pitches, 0) AS hit_by_pitches,
    COALESCE(ofs.strikeouts, 0) AS strikeouts,
    COALESCE(ofs.balls_in_play, 0) AS balls_in_play,
    COALESCE(ofs.runs, 0) AS runs,
    NULL::DOUBLE AS expected_plate_appearances,
    NULL::DOUBLE AS expected_at_bats,
    NULL::DOUBLE AS expected_hits,
    NULL::DOUBLE AS expected_singles,
    NULL::DOUBLE AS expected_doubles,
    NULL::DOUBLE AS expected_triples,
    NULL::DOUBLE AS expected_home_runs,
    NULL::DOUBLE AS expected_walks,
    NULL::DOUBLE AS expected_strikeouts,
    NULL::DOUBLE AS expected_balls_in_play,
    NULL::DOUBLE AS expected_runs,
    c.game_id,
    c.season,
    c.league,
    c.game_type,
    c.source_type,
    c.source_family,
    c.target_population_status,
    c.park_id,
    c.park_episode_status,
    c.scorer,
    c.inputter,
    c.translator,
    c.affiliated_team,
    c.inning_start,
    c.frame_start,
    c.base_state_start,
    c.outs_start,
    c.score_margin,
    c.leverage_index,
    c.leverage_bucket,
    c.runs_on_play,
    c.hit_or_out,
    c.batter_id,
    c.pitcher_id,
    c.batter_hand,
    c.pitcher_hand,
    c.batting_team_id,
    c.fielding_team_id,
    c.personnel_confidence,
    c.context_confidence,
    c.exposure_status,
    c.result_family,
    c.alignment_regime,
    p.dl_artifact_id,
    p.dl_p_class,
    p.dl_logit_class,
    STRUCT_PACK(
        is_heldout_scorer := s.is_heldout_scorer,
        is_heldout_park := s.is_heldout_park,
        is_heldout_alignment_regime := s.is_heldout_alignment_regime,
        is_heldout_source_acquisition_block := s.is_heldout_source_acquisition_block,
        is_heldout_season_block := s.is_heldout_season_block,
        is_heldout_aggregate_total := s.is_heldout_aggregate_total,
        is_heldout_player_group := s.is_heldout_player_group
    ) AS holdout_flags,
    CASE
        WHEN (HASH(c.game_id)::HUGEINT % 100) < 70 THEN 'TRAIN'
        WHEN (HASH(c.game_id)::HUGEINT % 100) < 85 THEN 'VALIDATE'
        ELSE 'TEST'
    END AS primary_fold,
    1.0 AS training_weight,
    @VAR('source_snapshot_id', 'dev') AS source_snapshot_id
FROM main_models.event_observation_context AS c
INNER JOIN main_models.event_states_full AS es USING (event_key)
LEFT JOIN ofs USING (event_key)
LEFT JOIN main_models.dl_proposal_manifest AS p
    ON p.event_key = c.event_key AND p.dimension = 'park_factors'
LEFT JOIN main_models.stress_holdout_registry AS s USING (event_key)
WHERE c.target_population_status = 'event_level'
