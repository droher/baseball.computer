MODEL (
  name main_models.model_input_observation_batted_ball,
  kind VIEW,
  description 'Modeling dataset: frozen observation surface for batted-ball geometry. One row per (event_key, dimension) emitted by event_observation_geometry, filtered to target_population_status = event_level. is_observed = (observed_status = observed). Carries shared event_observation_context covariates, DL-proposal manifest hooks (NULL until DL supplements land), and stress-test holdout flags packed into a STRUCT (NULL until split-registry lands). primary_fold derived inline via HASH(game_id) mod 100. training_weight = 1.0 when data_error_risk = none else 0.0. source_snapshot_id stamped from the source_snapshot_id var.',
  grain (event_key, dimension),
  columns (
    event_key UINTEGER,
    dimension VARCHAR,
    is_observed BOOLEAN,
    observed_status VARCHAR,
    sentinel_type VARCHAR,
    raw_value VARCHAR,
    mapped_value VARCHAR,
    deduced_value VARCHAR,
    value_origin VARCHAR,
    source_acquisition_status VARCHAR,
    data_error_risk VARCHAR,
    model_input_eligible BOOLEAN,
    game_id VARCHAR,
    season SMALLINT,
    league VARCHAR,
    game_type GAME_TYPE,
    source_type VARCHAR,
    source_family VARCHAR,
    target_population_status VARCHAR,
    park_id PARK_ID,
    park_episode_status VARCHAR,
    scorer VARCHAR,
    inputter VARCHAR,
    translator VARCHAR,
    affiliated_team TEAM_ID,
    inning_start UTINYINT,
    frame_start FRAME,
    base_state_start UTINYINT,
    outs_start UTINYINT,
    score_margin TINYINT,
    leverage_index DOUBLE,
    leverage_bucket VARCHAR,
    runs_on_play UTINYINT,
    hit_or_out BOOLEAN,
    batter_id VARCHAR,
    pitcher_id VARCHAR,
    batter_hand HAND,
    pitcher_hand HAND,
    batting_team_id TEAM_ID,
    fielding_team_id TEAM_ID,
    personnel_confidence VARCHAR,
    context_confidence VARCHAR,
    exposure_status VARCHAR,
    result_family VARCHAR,
    pa_result VARCHAR,
    alignment_regime VARCHAR,
    dl_artifact_id VARCHAR,
    dl_p_class DOUBLE[],
    propensity_p_observed DOUBLE,
    propensity_artifact_id VARCHAR,
    holdout_flags STRUCT(
      is_heldout_scorer BOOLEAN,
      is_heldout_park BOOLEAN,
      is_heldout_alignment_regime BOOLEAN,
      is_heldout_source_acquisition_block BOOLEAN,
      is_heldout_season_block BOOLEAN,
      is_heldout_aggregate_total BOOLEAN,
      is_heldout_player_group BOOLEAN
    ),
    primary_fold VARCHAR,
    training_weight DOUBLE,
    source_snapshot_id VARCHAR,
    geometry_target_contract VARCHAR
  ),
  column_descriptions (
    event_key = @doc('event_key'),
    dimension = 'Batted-ball geometry dimension. One row per (event_key, dimension), including separate global-side and within-zone-angle dimensions.',
    is_observed = 'BOOLEAN. TRUE iff observed_status = observed.',
    observed_status = 'event_observation_geometry.observed_status.',
    sentinel_type = 'event_observation_geometry.sentinel_type.',
    raw_value = 'event_observation_geometry.raw_value.',
    mapped_value = 'event_observation_geometry.mapped_value.',
    deduced_value = 'event_observation_geometry.deduced_value.',
    value_origin = 'event_observation_geometry.value_origin.',
    source_acquisition_status = 'event_observation_geometry.source_acquisition_status.',
    data_error_risk = 'event_observation_geometry.data_error_risk.',
    model_input_eligible = 'event_observation_geometry.model_input_eligible.',
    primary_fold = 'Default game-hash split. HASH(game_id) mod 100 -> [0,69]=TRAIN, [70,84]=VALIDATE, [85,99]=TEST.',
    training_weight = 'DOUBLE. 1.0 when data_error_risk = none, else 0.0. Allows the high-data-error rows to ride along for diagnostic queries without contaminating training.',
    source_snapshot_id = 'Stamp from the source_snapshot_id var. Carried through every modeling-dataset row so downstream exporters can identify the source-data snapshot the dataset was built against.',
    geometry_target_contract = 'Stable geometry target contract marker. geometry-v2-global-side identifies location_side as the taxonomy mapping of recorded general location.',
    holdout_flags = 'STRUCT of 7 stress-test holdout BOOLEANs, NULL until stress_holdout_registry materializes the split policy.',
    dl_artifact_id = 'dl_proposal_manifest.dl_artifact_id. Forced NULL for location_side until a geometry-v2-global-side dependency is validated.',
    dl_p_class = 'dl_proposal_manifest.dl_p_class. Forced NULL for location_side until a geometry-v2-global-side dependency is validated.',
    propensity_p_observed = 'scorer_observation_propensities.p_observed_mean. Forced NULL for location_side until a geometry-v2-global-side dependency is validated.',
    propensity_artifact_id = 'scorer_observation_propensities.artifact_id. Forced NULL for location_side until a geometry-v2-global-side dependency is validated.',
    pa_result = 'ml_event_outcomes.outcome_plate_appearance_cat (Single, Double, Triple, HomeRun, InPlayOut, ReachedOnError, SacrificeHit, SacrificeFly, StrikeOut, Walk, HitByPitch, IntentionalWalk, Other). NULL-coalesced to Other.'
  ),
  audits (
    not_null(columns := (event_key, dimension, observed_status, game_id, season, batting_team_id, fielding_team_id, primary_fold, source_snapshot_id)),
    unique_grain(columns := (event_key, dimension)),
    accepted_values(column := dimension, is_in := (
      'trajectory', 'location_side', 'location_angle', 'location_depth', 'location_edge',
      'general_location', 'ball_handler_position', 'pulled_opposite'
    )),
    accepted_values(column := primary_fold, is_in := ('TRAIN', 'VALIDATE', 'TEST')),
    accepted_values(column := target_population_status, is_in := ('event_level', 'aggregate_only', 'gamelog_only', 'structural_absence', 'out_of_scope', 'coverage_within_source_sparse')),
    accepted_values(column := source_family, is_in := ('play_by_play', 'box_score', 'gamelog', 'derived', 'absent')),
    accepted_values(column := alignment_regime, is_in := (
      'pre_shift_era', 'shift_growth_era', 'full_shift_era', 'post_restriction'
    )),
    accepted_values(column := leverage_bucket, is_in := ('low', 'medium', 'high')),
    accepted_values(column := pa_result, is_in := (
      'Single', 'Double', 'Triple', 'HomeRun', 'InPlayOut',
      'ReachedOnError', 'SacrificeHit', 'SacrificeFly',
      'StrikeOut', 'Walk', 'HitByPitch', 'IntentionalWalk', 'Other'
    )),
    relationships(column := event_key, to_model := main_models.event_observation_context, to_column := event_key)
  )
);

SELECT
    o.event_key,
    o.dimension,
    (o.observed_status = 'observed') AS is_observed,
    o.observed_status,
    o.sentinel_type,
    o.raw_value,
    o.mapped_value,
    o.deduced_value,
    o.value_origin,
    o.source_acquisition_status,
    o.data_error_risk,
    o.model_input_eligible,
    c.game_id,
    c.season,
    c.league,
    c.game_type,
    c.source_type,
    c.source_family,
    c.target_population_status,
    c.park_id,
    c.park_episode_status,
    c.scorer,
    c.inputter,
    c.translator,
    c.affiliated_team,
    c.inning_start,
    c.frame_start,
    c.base_state_start,
    c.outs_start,
    c.score_margin,
    c.leverage_index,
    c.leverage_bucket,
    c.runs_on_play,
    c.hit_or_out,
    c.batter_id,
    c.pitcher_id,
    c.batter_hand,
    c.pitcher_hand,
    c.batting_team_id,
    c.fielding_team_id,
    c.personnel_confidence,
    c.context_confidence,
    c.exposure_status,
    c.result_family,
    COALESCE(m.outcome_plate_appearance_cat, 'Other') AS pa_result,
    c.alignment_regime,
    CASE WHEN o.dimension = 'location_side' THEN NULL ELSE p.dl_artifact_id END AS dl_artifact_id,
    CASE WHEN o.dimension = 'location_side' THEN NULL ELSE p.dl_p_class END AS dl_p_class,
    CASE WHEN o.dimension = 'location_side' THEN NULL ELSE sp.p_observed_mean END AS propensity_p_observed,
    CASE WHEN o.dimension = 'location_side' THEN NULL ELSE sp.artifact_id END AS propensity_artifact_id,
    STRUCT_PACK(
        is_heldout_scorer := s.is_heldout_scorer,
        is_heldout_park := s.is_heldout_park,
        is_heldout_alignment_regime := s.is_heldout_alignment_regime,
        is_heldout_source_acquisition_block := s.is_heldout_source_acquisition_block,
        is_heldout_season_block := s.is_heldout_season_block,
        is_heldout_aggregate_total := s.is_heldout_aggregate_total,
        is_heldout_player_group := s.is_heldout_player_group
    ) AS holdout_flags,
    CASE
        WHEN (HASH(c.game_id)::HUGEINT % 100) < 70 THEN 'TRAIN'
        WHEN (HASH(c.game_id)::HUGEINT % 100) < 85 THEN 'VALIDATE'
        ELSE 'TEST'
    END AS primary_fold,
    CASE WHEN o.data_error_risk = 'none' THEN 1.0 ELSE 0.0 END AS training_weight,
    @VAR('source_snapshot_id', 'dev') AS source_snapshot_id,
    'geometry-v2-global-side' AS geometry_target_contract
FROM main_models.event_observation_geometry AS o
INNER JOIN main_models.event_observation_context AS c USING (event_key)
LEFT JOIN main_models.dl_proposal_manifest AS p
    ON p.event_key = o.event_key AND p.dimension = o.dimension
LEFT JOIN main_models.scorer_observation_propensities AS sp
    ON sp.event_key = o.event_key AND sp.dimension = o.dimension
LEFT JOIN main_models.ml_event_outcomes AS m USING (event_key)
LEFT JOIN main_models.stress_holdout_registry AS s USING (event_key)
WHERE c.target_population_status = 'event_level'
