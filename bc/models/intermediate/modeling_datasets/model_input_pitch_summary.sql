MODEL (
  name main_models.model_input_pitch_summary,
  kind VIEW,
  description 'Modeling dataset for the pitch-context / pitch-sequence model. One row per event_level event. Pivots event_observation_pitch per dimension into per-event raw_value columns and carries source_acquisition_status per dim for missingness diagnostics. has_count and has_pitch_sequence are coarse observation flags. Filtered to target_population_status = event_level.',
  grain (event_key),
  columns (
    event_key UINTEGER,
    count_balls_raw VARCHAR,
    count_balls_status VARCHAR,
    count_strikes_raw VARCHAR,
    count_strikes_status VARCHAR,
    pitch_sequence_raw VARCHAR,
    pitch_sequence_status VARCHAR,
    pitch_results_raw VARCHAR,
    pitch_results_status VARCHAR,
    strike_types_raw VARCHAR,
    strike_types_status VARCHAR,
    pitch_count_total_raw VARCHAR,
    pitch_count_total_status VARCHAR,
    has_count BOOLEAN,
    has_pitch_sequence BOOLEAN,
    game_id VARCHAR,
    season SMALLINT,
    league VARCHAR,
    game_type GAME_TYPE,
    source_type VARCHAR,
    source_family VARCHAR,
    target_population_status VARCHAR,
    park_id PARK_ID,
    park_episode_status VARCHAR,
    scorer VARCHAR,
    inputter VARCHAR,
    translator VARCHAR,
    affiliated_team TEAM_ID,
    inning_start UTINYINT,
    frame_start FRAME,
    base_state_start UTINYINT,
    outs_start UTINYINT,
    score_margin TINYINT,
    leverage_index DOUBLE,
    leverage_bucket VARCHAR,
    runs_on_play UTINYINT,
    hit_or_out BOOLEAN,
    batter_id VARCHAR,
    pitcher_id VARCHAR,
    batter_hand HAND,
    pitcher_hand HAND,
    batting_team_id TEAM_ID,
    fielding_team_id TEAM_ID,
    personnel_confidence VARCHAR,
    context_confidence VARCHAR,
    exposure_status VARCHAR,
    result_family VARCHAR,
    alignment_regime VARCHAR,
    dl_artifact_id VARCHAR,
    dl_p_class DOUBLE[],
    holdout_flags STRUCT(
      is_heldout_scorer BOOLEAN,
      is_heldout_park BOOLEAN,
      is_heldout_alignment_regime BOOLEAN,
      is_heldout_source_acquisition_block BOOLEAN,
      is_heldout_season_block BOOLEAN,
      is_heldout_aggregate_total BOOLEAN,
      is_heldout_player_group BOOLEAN
    ),
    primary_fold VARCHAR,
    training_weight DOUBLE,
    source_snapshot_id VARCHAR
  ),
  column_descriptions (
    event_key = @doc('event_key'),
    count_balls_raw = 'event_observation_pitch.raw_value where dimension = count_balls.',
    count_balls_status = 'event_observation_pitch.source_acquisition_status where dimension = count_balls.',
    count_strikes_raw = 'event_observation_pitch.raw_value where dimension = count_strikes.',
    count_strikes_status = 'event_observation_pitch.source_acquisition_status where dimension = count_strikes.',
    pitch_sequence_raw = 'event_observation_pitch.raw_value where dimension = pitch_sequence.',
    pitch_sequence_status = 'event_observation_pitch.source_acquisition_status where dimension = pitch_sequence.',
    pitch_results_raw = 'event_observation_pitch.raw_value where dimension = pitch_results.',
    pitch_results_status = 'event_observation_pitch.source_acquisition_status where dimension = pitch_results.',
    strike_types_raw = 'event_observation_pitch.raw_value where dimension = strike_types.',
    strike_types_status = 'event_observation_pitch.source_acquisition_status where dimension = strike_types.',
    pitch_count_total_raw = 'event_observation_pitch.raw_value where dimension = pitch_count_total.',
    pitch_count_total_status = 'event_observation_pitch.source_acquisition_status where dimension = pitch_count_total.',
    has_count = 'BOOL_OR(dimension IN (count_balls, count_strikes) AND observed_status = observed).',
    has_pitch_sequence = 'BOOL_OR(dimension = pitch_sequence AND observed_status = observed).',
    primary_fold = 'Default game-hash split. HASH(game_id) mod 100 -> [0,69]=TRAIN, [70,84]=VALIDATE, [85,99]=TEST.',
    training_weight = '1.0 universally.',
    source_snapshot_id = 'Stamp from the source_snapshot_id var.',
    holdout_flags = 'STRUCT of 7 stress-test holdout BOOLEANs, NULL until stress_holdout_registry materializes the split policy.',
    dl_artifact_id = 'dl_proposal_manifest.dl_artifact_id, NULL until DL supplements land.',
    dl_p_class = 'dl_proposal_manifest.dl_p_class, NULL until DL supplements land.'
  ),
  audits (
    not_null(columns := (event_key, game_id, season, primary_fold, source_snapshot_id)),
    unique_grain(columns := (event_key)),
    accepted_values(column := primary_fold, is_in := ('TRAIN', 'VALIDATE', 'TEST')),
    accepted_values(column := alignment_regime, is_in := (
      'pre_shift_era', 'shift_growth_era', 'full_shift_era', 'post_restriction'
    )),
    accepted_values(column := leverage_bucket, is_in := ('low', 'medium', 'high')),
    relationships(column := event_key, to_model := main_models.event_observation_context, to_column := event_key)
  )
);

WITH pivoted AS (
    SELECT
        event_key,
        MAX(CASE WHEN dimension = 'count_balls' THEN raw_value END) AS count_balls_raw,
        MAX(CASE WHEN dimension = 'count_balls' THEN source_acquisition_status END) AS count_balls_status,
        MAX(CASE WHEN dimension = 'count_strikes' THEN raw_value END) AS count_strikes_raw,
        MAX(CASE WHEN dimension = 'count_strikes' THEN source_acquisition_status END) AS count_strikes_status,
        MAX(CASE WHEN dimension = 'pitch_sequence' THEN raw_value END) AS pitch_sequence_raw,
        MAX(CASE WHEN dimension = 'pitch_sequence' THEN source_acquisition_status END) AS pitch_sequence_status,
        MAX(CASE WHEN dimension = 'pitch_results' THEN raw_value END) AS pitch_results_raw,
        MAX(CASE WHEN dimension = 'pitch_results' THEN source_acquisition_status END) AS pitch_results_status,
        MAX(CASE WHEN dimension = 'strike_types' THEN raw_value END) AS strike_types_raw,
        MAX(CASE WHEN dimension = 'strike_types' THEN source_acquisition_status END) AS strike_types_status,
        MAX(CASE WHEN dimension = 'pitch_count_total' THEN raw_value END) AS pitch_count_total_raw,
        MAX(CASE WHEN dimension = 'pitch_count_total' THEN source_acquisition_status END) AS pitch_count_total_status,
        BOOL_OR(dimension IN ('count_balls', 'count_strikes') AND observed_status = 'observed') AS has_count,
        BOOL_OR(dimension = 'pitch_sequence' AND observed_status = 'observed') AS has_pitch_sequence
    FROM main_models.event_observation_pitch
    GROUP BY event_key
)

SELECT
    c.event_key,
    pv.count_balls_raw,
    pv.count_balls_status,
    pv.count_strikes_raw,
    pv.count_strikes_status,
    pv.pitch_sequence_raw,
    pv.pitch_sequence_status,
    pv.pitch_results_raw,
    pv.pitch_results_status,
    pv.strike_types_raw,
    pv.strike_types_status,
    pv.pitch_count_total_raw,
    pv.pitch_count_total_status,
    COALESCE(pv.has_count, FALSE) AS has_count,
    COALESCE(pv.has_pitch_sequence, FALSE) AS has_pitch_sequence,
    c.game_id,
    c.season,
    c.league,
    c.game_type,
    c.source_type,
    c.source_family,
    c.target_population_status,
    c.park_id,
    c.park_episode_status,
    c.scorer,
    c.inputter,
    c.translator,
    c.affiliated_team,
    c.inning_start,
    c.frame_start,
    c.base_state_start,
    c.outs_start,
    c.score_margin,
    c.leverage_index,
    c.leverage_bucket,
    c.runs_on_play,
    c.hit_or_out,
    c.batter_id,
    c.pitcher_id,
    c.batter_hand,
    c.pitcher_hand,
    c.batting_team_id,
    c.fielding_team_id,
    c.personnel_confidence,
    c.context_confidence,
    c.exposure_status,
    c.result_family,
    c.alignment_regime,
    p.dl_artifact_id,
    p.dl_p_class,
    STRUCT_PACK(
        is_heldout_scorer := s.is_heldout_scorer,
        is_heldout_park := s.is_heldout_park,
        is_heldout_alignment_regime := s.is_heldout_alignment_regime,
        is_heldout_source_acquisition_block := s.is_heldout_source_acquisition_block,
        is_heldout_season_block := s.is_heldout_season_block,
        is_heldout_aggregate_total := s.is_heldout_aggregate_total,
        is_heldout_player_group := s.is_heldout_player_group
    ) AS holdout_flags,
    CASE
        WHEN (HASH(c.game_id)::HUGEINT % 100) < 70 THEN 'TRAIN'
        WHEN (HASH(c.game_id)::HUGEINT % 100) < 85 THEN 'VALIDATE'
        ELSE 'TEST'
    END AS primary_fold,
    1.0 AS training_weight,
    @VAR('source_snapshot_id', 'dev') AS source_snapshot_id
FROM main_models.event_observation_context AS c
LEFT JOIN pivoted AS pv USING (event_key)
LEFT JOIN main_models.dl_proposal_manifest AS p
    ON p.event_key = c.event_key AND p.dimension = 'pitch_summary'
LEFT JOIN main_models.stress_holdout_registry AS s USING (event_key)
WHERE c.target_population_status = 'event_level'
