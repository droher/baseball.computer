@DEF(stats, [inn1, inn2, inn3, inn4, inn5, inn6, inn7, inn8, inn9, inn10, inn11, inn12, inn13, inn14, inn15, inn16, inn17, inn18, inn19, inn20, inn21, inn22, inn23, inn24, inn25, inn26, inn27, inn28, lob, b_pa, b_ab, b_r, b_h, b_d, b_t, b_hr, b_rbi, b_sh, b_sf, b_hbp, b_w, b_iw, b_k, b_sb, b_cs, b_gdp, b_xi, b_roe, p_ipouts, p_noout, p_bfp, p_h, p_d, p_t, p_hr, p_r, p_er, p_w, p_iw, p_k, p_hbp, p_wp, p_bk, p_sh, p_sf, p_sb, p_cs, p_pb, d_po, d_a, d_e, d_dp, d_tp, d_pb, d_wp, d_sb, d_cs]);

