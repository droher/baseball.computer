        TRY_CAST(inn21 AS INTEGER) AS inn21,
        TRY_CAST(inn22 AS INTEGER) AS inn22,
        TRY_CAST(inn23 AS INTEGER) AS inn23,
        TRY_CAST(inn24 AS INTEGER) AS inn24,
